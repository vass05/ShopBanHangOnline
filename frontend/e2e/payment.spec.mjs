import { test, expect } from '@playwright/test';
import { register, addAddress, login, data, authorization, checkout, signedPayment, sql, waitMail } from './helpers.mjs';

test('multi-shop receipt is idempotent; signed return waits for IPN and invoice crosses RabbitMQ', async ({ page, request }) => {
  const user = await register(request, 'payment');
  const address = await addAddress(request, user);
  const { orders, body, headers } = await checkout(request, user, address, 'VNPAY', [{ skuId: 9001, quantity: 1 }, { skuId: 9002, quantity: 1 }]);
  expect(orders).toHaveLength(2);
  expect(orders.map(order => Number(order.shippingFee))).toEqual([30000, 30000]);
  const repeated = await data(await request.post('/api/v1/orders/checkout-batch', { headers, data: body }), 201);
  expect(repeated.map(order => order.id)).toEqual(orders.map(order => order.id));
  const order = orders[0];
  const payment = await data(await request.post('/api/v1/payments/create-vnpay-url', { headers: authorization(user), data: { orderCode: order.orderCode } }));
  const url = new URL(payment.paymentUrl);
  expect(url.searchParams.get('vnp_TxnRef')).toBe(order.orderCode);
  expect(url.searchParams.get('vnp_Amount')).toBe(String(Number(order.finalAmount) * 100));
  expect(url.searchParams.get('vnp_ReturnUrl')).toBe('http://localhost:18000/payment-result');
  await login(page, user);
  const callback = signedPayment(order);
  await page.goto(`/payment-result?${new URLSearchParams(callback)}`);
  await expect(page.getByRole('heading', { name: 'Đang chờ xác nhận thanh toán' })).toBeVisible();
  let current = await data(await request.get(`/api/v1/orders/${order.id}`, { headers: authorization(user) }));
  expect(current.paymentStatus).toBe('PENDING');
  const invalid = { ...callback, vnp_Amount: '100' };
  expect((await (await request.get('/api/v1/payments/vnpay-ipn', { params: invalid })).json()).RspCode).toBe('97');
  const wrongAmount = signedPayment(order, { vnp_Amount: '100' });
  expect((await (await request.get('/api/v1/payments/vnpay-ipn', { params: wrongAmount })).json()).RspCode).toBe('04');
  const results = await Promise.all(Array.from({ length: 4 }, () => request.get('/api/v1/payments/vnpay-ipn', { params: callback }).then(response => response.json())));
  expect(results.filter(result => result.RspCode === '00')).toHaveLength(1);
  expect(results.filter(result => result.RspCode === '02')).toHaveLength(3);
  await expect(page.getByRole('heading', { name: 'Thanh toán thành công' })).toBeVisible();
  current = await data(await request.get(`/api/v1/orders/${order.id}`, { headers: authorization(user) }));
  expect(current.paymentStatus).toBe('PAID');
  expect(current.orderStatus).toBe('PROCESSING');
  const id = Number(order.id);
  expect(Number.isSafeInteger(id)).toBeTruthy();
  expect(sql(`SELECT COUNT(*) FROM payment_transactions WHERE order_id=${id};`)).toBe('1');
  expect(sql(`SELECT COUNT(*) FROM order_paid_outbox WHERE order_id=${id};`)).toBe('1');
  const mail = await waitMail(request, user.email, order.orderCode);
  expect(mail.HTML).toContain(order.orderCode);
  await expect.poll(() => sql(`SELECT CONCAT(CAST(email_published AS UNSIGNED),':',CAST(seller_published AS UNSIGNED)) FROM order_paid_outbox WHERE order_id=${id};`)).toBe('1:1');
});
