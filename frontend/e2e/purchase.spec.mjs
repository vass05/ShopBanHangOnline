import { test, expect } from '@playwright/test';
import { register, addAddress, login, data, authorization, browserUser, stock, redis } from './helpers.mjs';

test('browser COD purchase uses Redis/MySQL and cancellation restores stock exactly once', async ({ page, request }) => {
  const user = await register(request, 'cod');
  await addAddress(request, user);
  const initial = await stock(request);
  await login(page, user);
  await page.goto('/product/9001');
  await expect(page.getByText('E2E Blue Shirt', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Thêm Vào Giỏ Hàng', exact: true }).click();
  await expect(page.getByText('Đã thêm vào giỏ hàng thành công!', { exact: true })).toBeVisible();
  expect(redis('TYPE', `cart:user:${user.userId}`)).toBe('hash');
  const ttl = Number(redis('TTL', `cart:user:${user.userId}`));
  expect(ttl).toBeGreaterThan(2_591_900);
  expect(ttl).toBeLessThanOrEqual(2_592_000);
  await page.goto('/cart');
  await expect(page.getByText('E2E Blue Shirt', { exact: true }).first()).toBeVisible();
  const selectAll = page.getByRole('checkbox').first();
  await selectAll.setChecked(true);
  await page.getByRole('button', { name: /Mua Hàng \(1\)/ }).click();
  await expect(page).toHaveURL(/\/checkout/);
  await expect(page.getByRole('button', { name: 'Đặt hàng', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Đặt hàng', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Đã tạo 1 đơn hàng' })).toBeVisible();
  const session = await browserUser(page);
  const orders = await data(await request.get('/api/v1/orders/me', { headers: authorization(session) }));
  expect(orders).toHaveLength(1);
  const order = orders[0];
  expect(order.paymentMethod).toBe('COD');
  expect(order.paymentStatus).toBe('UNPAID');
  expect(Number(order.finalAmount)).toBe(155000);
  expect(await stock(request)).toBe(initial - 1);
  expect(redis('HLEN', `cart:user:${user.userId}`)).toBe('0');
  const other = await register(request, 'stranger');
  expect((await request.get(`/api/v1/orders/${order.id}`, { headers: authorization(other) })).status()).toBe(403);
  await page.reload();
  await page.goto('/orders');
  const article = page.locator('article').filter({ hasText: order.orderCode });
  await expect(article).toContainText('Chờ xác nhận');
  page.once('dialog', dialog => dialog.accept());
  await article.getByRole('button', { name: 'Hủy đơn', exact: true }).click();
  await expect(article).toContainText('Đã hủy');
  expect(await stock(request)).toBe(initial);
  await request.patch(`/api/v1/orders/${order.id}/status?status=CANCELLED`, { headers: authorization(session) });
  expect(await stock(request)).toBe(initial);
  await page.reload();
  await expect(page.locator('article').filter({ hasText: order.orderCode })).toContainText('Đã hủy');
});
